/**
 * Helper to get translation for a key in the given language, falling back to Hindi or English.
 */
export function getTranslation(key: string, lang: string = 'en', fallbackText?: string): string {
  const langDict = TRANSLATIONS[lang];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Fallback to Hindi if not English, or English
  if (lang !== 'en' && TRANSLATIONS['hi'] && TRANSLATIONS['hi'][key]) {
    return TRANSLATIONS['hi'][key];
  }
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return fallbackText || key;
}
