export const ALL_DISTRICT_NAMES = INDIAN_LOCATIONS.flatMap(loc => 
  loc.districts.map(d => d.name)
);

export const ALL_MARKETS = INDIAN_LOCATIONS.flatMap(loc => 
  loc.districts.flatMap(d => d.markets.map(m => `${m}, ${loc.state}`))
);

export const ALL_DISTRICT_OBJECTS = INDIAN_LOCATIONS.flatMap(loc => 
  loc.districts.map(d => ({
    name: d.name,
    state: loc.state,
    label: `${d.name}, ${loc.state}`,
    markets: d.markets
  }))
);

export function getDistrictsForState(stateName) {
  if (!stateName) return [];
  const found = INDIAN_LOCATIONS.find(l => l.state.toLowerCase() === stateName.toLowerCase());
  return found ? found.districts.map(d => d.name) : [];
}

export function getMarketsForDistrict(stateName, districtName) {
  if (!stateName || !districtName) return [];
  const stateObj = INDIAN_LOCATIONS.find(l => l.state.toLowerCase() === stateName.toLowerCase());
  if (!stateObj) return [];
  const distObj = stateObj.districts.find(d => d.name.toLowerCase() === districtName.toLowerCase());
  return distObj ? distObj.markets : [];
}
